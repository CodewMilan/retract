/** Writes synthetic projects to an explicitly selected local server.
 * Start Retract against an isolated graph, then run:
 * node tests/dashboard-journey.browser.mjs http://127.0.0.1:8111
 */
import assert from 'node:assert/strict';
import {mkdir, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {chromium} from 'playwright';
const target = new URL(process.argv[2] || 'http://127.0.0.1:8111');
if (target.protocol !== 'http:' || !['127.0.0.1', 'localhost'].includes(target.hostname)) throw new Error('Use an isolated local server. This check creates synthetic projects.');
const dir = resolve('reports/ux-review/journeys'); await mkdir(dir, {recursive: true});
const browser = await chromium.launch({headless: true});
const results = [];
try {
  for (const width of [375, 768, 1024, 1440]) {
    const context = await browser.newContext({viewport: {width, height: 1000}, reducedMotion: 'reduce'});
    const page = await context.newPage(); page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    const name = `UX journey ${width} ${Date.now()}`;
    const connected = () => page.waitForFunction(() => document.querySelector('#connection')?.textContent === 'Storage connected');
    const menu = async () => { if (width <= 760 && await page.locator('#menu-toggle').getAttribute('aria-expanded') !== 'true') await page.locator('#menu-toggle').click(); };
    const navigate = async view => { await menu(); await page.locator(`[data-view="${view}"]`).click(); };
    const shot = name => page.screenshot({path: resolve(dir, `${width}-${name}.png`), fullPage: true});
    await page.goto(new URL('/dashboard', target).href); await connected();
    await menu(); await page.locator('#new-project').click();
    await page.getByLabel('Project name', {exact: false}).fill(name);
    const project = await page.locator('#project-id').inputValue();
    await shot('create-project');
    await page.locator('#project-form button[type=submit]').click();
    await page.getByRole('heading', {name: 'What should your next agent know?'}).waitFor();
    assert.equal(await page.locator('#title').innerText(), 'Memory');
    assert.equal(await page.locator('#project').inputValue(), project);
    await shot('first-memory');
    await page.getByRole('button', {name: 'Add your first memory', exact: true}).click();
    await page.locator('#subject').fill('Authentication');
    await page.locator('#fact-value').fill('Use bearer tokens');
    await page.locator('#fact-evidence').fill('Approved architecture decision: Use bearer tokens for authentication.');
    await page.locator('#fact-authority').check();
    await shot('add-memory');
    await page.locator('#remember-form button[type=submit]').click();
    await page.locator('#records .record').filter({hasText: 'Use bearer tokens'}).waitFor();
    assert.equal(await page.locator('#start-guide').isVisible(), false);
    await page.locator('#new-plan').click();
    await page.locator('#plan-text').fill('Build account settings using bearer tokens.');
    await page.locator('#plan-dependencies input').first().check();
    await shot('new-plan');
    await page.locator('#plan-form button[type=submit]').click();
    await page.getByRole('heading', {name: 'Plans', exact: true}).waitFor();
    await page.locator('#records .record').filter({hasText: 'Build account settings using bearer tokens.'}).waitFor();
    await navigate('active');
    await page.locator('#records .record').first().click();
    await page.getByRole('button', {name: 'Update this decision', exact: true}).click();
    assert.equal(await page.locator('#mode').inputValue(), 'structured');
    await page.locator('#replacement').fill('HTTP-only cookie sessions');
    await page.locator('#update-text').fill('Approved change: use HTTP-only cookie sessions for authentication.');
    await page.locator('#authority').check(); await page.locator('#confirmation').check();
    await shot('update-decision');
    await page.locator('#update-form button[type=submit]').click();
    await page.locator('#review-banner').getByRole('button', {name: 'Review plans', exact: true}).waitFor();
    assert.ok((await page.locator('#records').innerText()).includes('HTTP-only cookie sessions'));
    await page.locator('#review-banner').getByRole('button', {name: 'Review plans', exact: true}).click();
    await page.locator('#records .record').first().click();
    assert.ok((await page.locator('#inspector').innerText()).includes('Replaced'));
    await shot('needs-review');
    await page.getByRole('button', {name: 'Review and revise plan', exact: true}).click();
    assert.equal(await page.locator('#plan-dependencies input:checked').count(), 0);
    await page.locator('#plan-text').fill('Build account settings using HTTP-only cookie sessions.');
    await page.locator('#plan-dependencies input').first().check();
    await page.locator('#plan-reason').fill('Authentication now uses cookie sessions.');
    await page.locator('#plan-confirmation').check();
    await shot('revise-plan');
    await page.locator('#plan-form button[type=submit]').click();
    await page.locator('#records .record').filter({hasText: 'Build account settings using HTTP-only cookie sessions.'}).waitFor();
    await navigate('affected');
    await page.getByRole('heading', {name: 'Your plans are up to date', exact: true}).waitFor();
    await shot('review-complete');
    await navigate('active');
    await page.locator('#records .record').first().click();
    await page.locator('#inspector .source-details summary').click();
    assert.ok((await page.locator('#inspector .source-details').innerText()).includes('Approved change: use HTTP-only cookie sessions'));
    await shot('source-evidence');
    await page.getByRole('button', {name: 'Close details', exact: true}).click();
    await page.locator('#search').fill('cookie');
    await page.waitForURL(url => url.searchParams.get('q') === 'cookie');
    const sharedUrl = page.url(); await page.reload(); await connected();
    assert.equal(page.url(), sharedUrl); assert.equal(await page.locator('#records .record').count(), 1);
    await page.locator('#clear-search').click();
    await page.locator('#title').focus(); await page.keyboard.press('/');
    assert.equal(await page.locator('#search').evaluate(node => node === document.activeElement), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    const response = await page.request.post(new URL('/dashboard', target).href, {data: {project_id: project}});
    const snapshot = await response.json();
    assert.equal(snapshot.counts.active, 1); assert.equal(snapshot.counts.superseded, 1); assert.equal(snapshot.counts.affected, 0);
    assert.equal(snapshot.plans.filter(plan => plan.status === 'current').length, 1);
    assert.equal(snapshot.plans.filter(plan => plan.status === 'superseded').length, 1);
    results.push({width, project, revision: snapshot.project.revision, passed: true});
    console.log(`PASS ${width}px: real project → memory → linked plan → correction → review → revision → source → reload`);
    await context.close();
  }
  await writeFile(resolve(dir, 'results.json'), JSON.stringify({target: target.origin, results}, null, 2));
} finally { await browser.close(); }
